"""SQLAlchemy Table Definitions for SafeSpec.

Tables created:
1. runs: Pipeline execution runs and high-level KPI metrics
2. requirements: Ingested automotive requirements and flags
3. rules: Structured checkable rules in fixed format (Rule 5)
4. tests: Executable test cases (Rule 4)
5. results: Test execution results against simulated ECU
6. fixes: Candidate fixes and rewrites generated by agent
7. approvals: Engineer approval gate queue for safety & conflicts (Rule 9)
8. agent_log: Audit trail of every thought, tool call, and result (Rule 8)
9. memories: Vector/semantic and associative retrieval memories
10. ecu_versions: Immutable version history of ECU control logic (Rule 10)
"""

from datetime import datetime, timezone
import json
from sqlalchemy import (
    Column,
    Integer,
    String,
    Text,
    Boolean,
    Float,
    DateTime,
)
from sqlalchemy.orm import declarative_base

Base = declarative_base()


class RunTable(Base):
    """Pipeline execution runs and aggregated KPIs."""

    __tablename__ = "runs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    run_id = Column(String(64), unique=True, index=True, nullable=False)
    pipeline_stage = Column(String(64), default="idle", nullable=False)
    status = Column(String(32), default="running", nullable=False)  # running, completed, failed
    total_requirements = Column(Integer, default=0, nullable=False)
    flagged_count = Column(Integer, default=0, nullable=False)
    tests_passed = Column(Integer, default=0, nullable=False)
    tests_failed = Column(Integer, default=0, nullable=False)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
    completed_at = Column(DateTime, nullable=True)
    run_state_json = Column(Text, nullable=True)

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "run_id": self.run_id,
            "pipeline_stage": self.pipeline_stage,
            "status": self.status,
            "total_requirements": self.total_requirements,
            "flagged_count": self.flagged_count,
            "tests_passed": self.tests_passed,
            "tests_failed": self.tests_failed,
            "created_at": self.created_at.isoformat() if self.created_at else None,
            "completed_at": self.completed_at.isoformat() if self.completed_at else None,
        }


class RequirementTable(Base):
    """Ingested automotive requirements."""

    __tablename__ = "requirements"

    id = Column(String(32), primary_key=True, index=True)
    text = Column(Text, nullable=False)
    flags = Column(Text, default="[]", nullable=False)  # JSON list
    terms = Column(Text, default="[]", nullable=False)  # JSON list
    safety = Column(Boolean, default=False, nullable=False)
    asil = Column(String(8), default="QM", nullable=False)
    regulation = Column(String(128), nullable=True)
    chunk_id = Column(String(64), nullable=True)
    chunk_text = Column(Text, nullable=True)
    note = Column(Text, nullable=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "text": self.text,
            "flags": json.loads(self.flags) if self.flags else [],
            "terms": json.loads(self.terms) if self.terms else [],
            "safety": self.safety,
            "asil": self.asil,
            "regulation": self.regulation,
            "chunk_id": self.chunk_id,
            "chunk_text": self.chunk_text,
            "note": self.note,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class RuleTable(Base):
    """Structured checkable rules in fixed format (Rule 5)."""

    __tablename__ = "rules"

    id = Column(String(32), primary_key=True, index=True)
    text = Column(Text, nullable=False)
    condition_json = Column(Text, nullable=False)  # JSON dict {var, op, value}
    action_json = Column(Text, nullable=False)  # JSON dict {var, op, value}
    asil = Column(String(8), default="QM", nullable=False)
    regulation = Column(String(128), nullable=True)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "text": self.text,
            "condition": json.loads(self.condition_json),
            "action": json.loads(self.action_json),
            "asil": self.asil,
            "regulation": self.regulation,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


class TestTable(Base):
    """Test specifications generated deterministically for ECU simulation (Rule 4)."""

    __test__ = False  # Instruct pytest not to treat this table as a test class

    __tablename__ = "tests"

    id = Column(String(32), primary_key=True, index=True)  # e.g. T-01
    req_id = Column(String(32), index=True, nullable=False)
    name = Column(String(255), nullable=False)
    scenario = Column(Text, nullable=True)
    given_json = Column(Text, default="{}", nullable=False)
    expected = Column(String(128), nullable=False)
    latency = Column(Float, nullable=True)
    is_assumed = Column(Boolean, default=False, nullable=False)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "req_id": self.req_id,
            "name": self.name,
            "scenario": self.scenario,
            "given": json.loads(self.given_json) if self.given_json else {},
            "expected": self.expected,
            "latency": self.latency,
            "is_assumed": self.is_assumed,
            "created_at": self.created_at.isoformat() if self.created_at else None,
        }


